def clean_title(title):
    t = title.strip()
    t = re.sub(r'\s*\d+[-~]\d*人?\s*(开放|封闭|半开放)?\s*$', '', t)
    t = re.sub(r'\s*\d+人?\s*(开放|封闭|半开放)?\s*$', '', t)
    t = t.replace("《", "").replace("》", "").strip()
    return t

def match_juben_type(title):
    ct = clean_title(title)
    if ct in muban_types:
        return muban_types[ct]
    if ct in MANUAL_TYPES:
        return MANUAL_TYPES[ct]
    for kw, jtype in KEYWORD_TYPE_MAP.items():
        if kw in title:
            return jtype
    return ""

d = json.load(open('data.json', 'r', encoding='utf-8'))
unmatched = []

for item in d:
    if item.get('type') == '剧本杀' and not item.get('juben_type'):
        title = item.get('title', '')
        juben_type = match_juben_type(title)
        if juben_type:
            item['juben_type'] = juben_type
        else:
            # 额外修复
            if title in EXTRA_FIXES:
                item['juben_type'] = EXTRA_FIXES[title]
            else:
                unmatched.append(title)

